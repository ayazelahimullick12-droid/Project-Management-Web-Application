/**
 * Read view of a document: sections with comment and suggestion highlights.
 * Selecting text shows a small toolbar to comment or suggest new wording.
 */
import { MessageSquarePlus, PenLine } from 'lucide-react'
import { useRef, useState } from 'react'
import type { Section } from '../../types'
import { Markdown, type Highlight } from '../../components/Markdown'
import { contextAround, findQuote, markdownToPlain, normalize } from '../../rules/text'

export interface Selection {
  sectionId: string
  sectionTitle: string
  quote: string
  prefix: string
  suffix: string
}

export function Reader({ sections, highlights, canAnnotate, onAnnotate, activeId, onHighlightClick, regenerated }: {
  sections: Section[]
  highlights: (Highlight & { sectionId: string | null })[]
  canAnnotate: boolean
  onAnnotate: (kind: 'comment' | 'suggest', sel: Selection) => void
  activeId?: string
  onHighlightClick?: (id: string) => void
  regenerated?: string[]
}) {
  const box = useRef<HTMLDivElement>(null)
  const [toolbar, setToolbar] = useState<{ x: number; y: number; sel: Selection } | null>(null)

  const onMouseUp = () => {
    if (!canAnnotate) return
    const s = window.getSelection()
    if (!s || s.isCollapsed) return setToolbar(null)
    const text = normalize(s.toString())
    if (text.length < 2) return setToolbar(null)
    const anchor = (s.anchorNode instanceof Element ? s.anchorNode : s.anchorNode?.parentElement)?.closest('[data-section]')
    const focus = (s.focusNode instanceof Element ? s.focusNode : s.focusNode?.parentElement)?.closest('[data-section]')
    if (!anchor || anchor !== focus) return setToolbar(null) // one section at a time
    const sectionId = anchor.getAttribute('data-section')!
    const section = sections.find((x) => x.id === sectionId)!
    const plain = markdownToPlain(section.content)
    const idx = findQuote(plain, text)
    const ctx = idx >= 0 ? contextAround(plain, idx, text.length) : { prefix: '', suffix: '' }
    const rect = s.getRangeAt(0).getBoundingClientRect()
    const outer = box.current!.getBoundingClientRect()
    setToolbar({ x: rect.left - outer.left + rect.width / 2, y: rect.top - outer.top - 8, sel: { sectionId, sectionTitle: section.title, quote: text, ...ctx } })
  }

  return (
    <div ref={box} className="relative" onMouseUp={onMouseUp}>
      {toolbar && (
        <div className="absolute z-20 flex -translate-x-1/2 -translate-y-full gap-1 rounded-md bg-ink p-1 shadow-lg no-print" style={{ left: toolbar.x, top: toolbar.y }} onMouseDown={(e) => e.preventDefault()}>
          <button className="flex items-center gap-1 rounded px-2 py-1 text-xs text-white hover:bg-white/15" onClick={() => { onAnnotate('comment', toolbar.sel); setToolbar(null) }}>
            <MessageSquarePlus className="h-3.5 w-3.5" /> Comment
          </button>
          <button className="flex items-center gap-1 rounded px-2 py-1 text-xs text-white hover:bg-white/15" onClick={() => { onAnnotate('suggest', toolbar.sel); setToolbar(null) }}>
            <PenLine className="h-3.5 w-3.5" /> Suggest wording
          </button>
        </div>
      )}
      {sections.map((s) => (
        <section key={s.id} className="mb-6" data-section={s.id}>
          <h2 className="mb-2 flex items-center gap-2 text-lg font-semibold">
            {s.title}
            {regenerated?.includes(s.id) && <span className="rounded bg-violet-50 px-1.5 py-0.5 text-[10px] font-medium text-violet-700 ring-1 ring-violet-200">regenerated by AI in this version</span>}
          </h2>
          <Markdown
            text={s.content}
            highlights={highlights.filter((h) => h.sectionId === s.id).map((h) => ({ ...h, active: h.id === activeId }))}
            onHighlightClick={onHighlightClick}
          />
        </section>
      ))}
    </div>
  )
}
